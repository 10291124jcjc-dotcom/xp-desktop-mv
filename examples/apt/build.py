class Cursor:
    def __init__(self):
        self.keys, self.clicks, self.hide = [], [], []
    def at(self, t, x, y, ease="inOut"):
        self.keys.append({"t": t, "x": round(x, 1), "y": round(y, 1), "ease": ease})
        return self
    def click(self, t):
        # the pointer must still be on the target when the button goes down: hold the last position until the click
        last = self.keys[-1]
        self.keys.append({"t": t, "x": last["x"], "y": last["y"], "ease": "linear"})
        self.clicks.append(t)
        return self
    def wiggle(self, k0, x, y, amp, n, step=0.0625):
        """quick left-right shakes starting at bar k0, one swing per `step` bars"""
        for i in range(n):
            self.at(bar(k0 + i * step), x + (amp if i % 2 == 0 else -amp), y, "out")
        return self.at(bar(k0 + n * step), x, y, "out")
    def dump(self):
        return {"keys": self.keys, "clicks": self.clicks, "hide": self.hide}

def err(id_, t0, t1, x, y, text, glyph="error", buttons=("确定",), w=330, h=130, z=10, **kw):
    d = {"id": id_, "type": "error", "t0": t0, "t1": t1, "x": x, "y": y, "w": w, "h": h, "z": z,
         "title": kw.pop("title", "APT."), "text": text, "glyph": glyph, "buttonsList": list(buttons)}
    d.update(kw)
    return d

def write(name, data):
    data["_note"] = "generated by shots/build.py - edit the generator, not this file"
    (HERE / name).write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")

