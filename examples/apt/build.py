def bar(k, off=0.0):
    s = f"bar:{round(k, 4)}"
    if off:
        s += f"{off:+.3f}"
    return s

def sec(k, off=0.0):
    return BAR0 + k * 4 * P + off

# ---------------------------------------------------------------- engine geometry (logical 960x540)
TB = 26
def client(x, y, w, h):
    return x + 4, y + TB + 1, w - 8, h - TB - 5

def dialog_button(win, i, corner=False):
    """Screen position of button i in a dialog (labels all measure 78px), honouring the dialog's scale.
    corner=True gives a point near the button's lower-right so the arrow does not cover the label."""
    cx, cy, cw, ch = client(win["x"], win["y"], win["w"], win["h"])
    n = len(win.get("buttonsList", ["确定"]))
    total = 78 * n + 8 * (n - 1)
    bx = cx + (cw - total) / 2 + i * 86
    by = cy + ch - 12 - 25
    px, py = (bx + 66, by + 20) if corner else (bx + 39, by + 12.5)
    s = win.get("scale", 1)
    mx, my = win["x"] + win["w"] / 2, win["y"] + win["h"] / 2
    return round(mx + (px - mx) * s, 1), round(my + (py - my) * s, 1)

def to_local_delta(win, screen_from, screen_to):
    s = win.get("scale", 1)
    return round((screen_to[0] - screen_from[0]) / s, 1), round((screen_to[1] - screen_from[1]) / s, 1)

