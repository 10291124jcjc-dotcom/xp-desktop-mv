"""Generate shots/ch01.json ... ch06.json.

Every time is written as a beat reference ("bar:K" = start of bar K, fractional K = beats/4, optional +/-seconds)
so the engine resolves it against analysis/beats.json (and snaps it to the 30fps frame grid).
Bar 0 starts at the first downbeat (1.108 s). Geometry helpers mirror the engine's layout so the cursor
lands exactly on buttons, icons and title bars.
"""
